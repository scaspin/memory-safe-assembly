def itx_names(symbols, obj):
    return [
        s
        for f, s in symbols
        if f == obj and s.startswith("inv_txfm_add_") and re.search(r"_\d+x\d+_", s)
    ]


def main():
    symbols_path = sys.argv[1] if len(sys.argv) > 1 else "asm-symbols.tsv"
    symbols = [l.rstrip("\n").split("\t") for l in open(symbols_path) if l.strip()]

    os.makedirs(OUT_DIR, exist_ok=True)
    modules = {
        "ipred": ("Intra prediction (ipred.S, ipred16.S)", gen_ipred(8) + gen_ipred(16)),
        "itx": (
            "Inverse transforms (itx.S, itx16.S)",
            gen_itx(8, itx_names(symbols, "itx"))
            + gen_itx(16, itx_names(symbols, "itx16")),
        ),
        "mc": (
            "Motion compensation (mc.S, mc16.S, mc_dotprod.S)",
            gen_mc(8) + gen_mc(16) + gen_mc_dotprod(),
        ),
        "cdef": ("Constrained directional enhancement (cdef.S, cdef16.S)", gen_cdef(8) + gen_cdef(16)),
        "loopfilter": ("Deblocking loop filter (loopfilter.S, loopfilter16.S)", gen_loopfilter(8) + gen_loopfilter(16)),
        "looprestoration": (
            "Loop restoration (looprestoration.S, looprestoration16.S, looprestoration_common.S)",
            gen_looprestoration(8) + gen_looprestoration(16) + gen_looprestoration_common(),
        ),
        "filmgrain": ("Film grain synthesis (filmgrain.S, filmgrain16.S)", gen_filmgrain(8) + gen_filmgrain(16)),
        "msac": ("Multi-symbol arithmetic decoder (msac.S)", gen_msac()),
        "refmvs": ("Reference motion vectors (refmvs.S)", gen_refmvs()),
    }

    count = 0
    for name, (title, body) in sorted(modules.items()):
        path = os.path.join(OUT_DIR, f"{name}.rs")
        with open(path, "w") as fh:
            fh.write(HEADER.format(title=title))
            fh.write(body)
            fh.write("\n")
        n = body.count("check_mem_safe")
        count += n
        print(f"{name}.rs: {n} declarations")

    with open(os.path.join(OUT_DIR, "mod.rs"), "w") as fh:
        fh.write("//! Annotated declarations for rav1d's aarch64 assembly.\n")
        fh.write("//!\n//! Generated by `gen-annotations.py`.\n\n")
        for name in sorted(modules):
            fh.write(f"pub mod {name};\n")

    print(f"TOTAL: {count} declarations")


if __name__ == "__main__":
    main()
