def row_pointers(array, buf, element, rows, stride=400):
    """Row pointers stated as real offsets into their backing buffer, so each
    row's extent comes from that slice's own length and the equality itself is
    checked at the call. rav1d builds them as `buf[i * BUF_STRIDE..]`, and
    rotates them, so the offsets stay parameters."""
    clauses = [f"{array}[{i}] == {buf}.as_mut_ptr().add(o_{buf}{i})" for i in range(rows)]
    clauses += [f"o_{buf}{i} + {stride} <= {buf}.len()" for i in range(rows)]
    params = [f"{buf}: &mut [{element}]"] + [f"o_{buf}{i}: usize" for i in range(rows)]
    return clauses, params


