# mc.S / mc16.S / mc_dotprod.S
# ---------------------------------------------------------------------------

FILTERS = [
    "regular",
    "regular_smooth",
    "regular_sharp",
    "smooth",
    "smooth_regular",
    "smooth_sharp",
    "sharp",
    "sharp_regular",
    "sharp_smooth",
]


# A subpel filter reads a window around the block: `before` rows above and
# columns left of it, `after` rows below and columns right of it. The slice is
# that whole window and the pointer handed to the assembly sits at its block
# corner, so the lowest access is slice offset 0 and the highest is
# `(h - 1 + before + after) * stride + w - 1 + before + after`.
def src_window(before, after):
    span = before + after
    pointer = f"src.as_ptr().add({before} * src_stride + {before})" if before else "src.as_ptr()"
    length = f"src.len() == src_stride * (h + {span - 1}) + w + {span}"
    return pointer, length


def mc_put(f, name, px, before=3, after=4):
    pointer, length = src_window(before, after)
    return f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), dst_stride, {pointer}, src_stride, w, h, mx, my, bitdepth_max,
    [dst.len() == dst_stride * h, {length}, w >= 2, h >= 2, w <= 128, h <= 128, 128 % h == 0, dst_stride >= w, src_stride >= w, mx >= 0, mx <= 15, my >= 0, my <= 15])]
fn {name}(
    dst: &mut [{px}],
    dst_stride: usize,
    src: &[{px}],
    src_stride: usize,
    w: usize,
    h: usize,
    mx: i32,
    my: i32,
    bitdepth_max: i32,
);'''


def mc_prep(f, name, px, before=3, after=4):
    pointer, length = src_window(before, after)
    return f'''
#[bums::check_mem_safe("{f}", tmp.as_mut_ptr(), {pointer}, src_stride, w, h, mx, my, bitdepth_max,
    [tmp.len() == w * h, {length}, w >= 4, h >= 4, w <= 128, h <= 128, 128 % h == 0, src_stride >= w, mx >= 0, mx <= 15, my >= 0, my <= 15])]
fn {name}(
    tmp: &mut [i16],
    src: &[{px}],
    src_stride: usize,
    w: usize,
    h: usize,
    mx: i32,
    my: i32,
    bitdepth_max: i32,
);'''


def gen_mc(bpc):
    px = pixel(bpc)
    sfx = suffix(bpc)
    elem = 1 if bpc == 8 else 2
    f = f"mc{'' if bpc == 8 else '16'}.S"
    out = []

    for filt in FILTERS:
        out.append(mc_put(f, f"put_8tap_{filt}{sfx}", px))
    out.append(mc_put(f, f"put_bilin{sfx}", px, before=0, after=2))
    for filt in FILTERS:
        out.append(mc_prep(f, f"prep_8tap_{filt}{sfx}", px))
    out.append(mc_prep(f, f"prep_bilin{sfx}", px, before=0, after=2))

    # avg / w_avg / mask
    out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, tmp1.as_ptr(), tmp2.as_ptr(), w, h, bitdepth_max,
    [dst.len() == stride * h, tmp1.len() == w * h, tmp2.len() == w * h, w >= 4, h >= 4, w <= 128, h <= 128, 128 % h == 0, stride >= w])]
fn avg{sfx}(dst: &mut [{px}], stride: usize, tmp1: &[i16], tmp2: &[i16], w: usize, h: usize, bitdepth_max: i32);

#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, tmp1.as_ptr(), tmp2.as_ptr(), w, h, weight, bitdepth_max,
    [dst.len() == stride * h, tmp1.len() == w * h, tmp2.len() == w * h, w >= 4, h >= 4, w <= 128, h <= 128, 128 % h == 0, stride >= w])]
fn w_avg{sfx}(dst: &mut [{px}], stride: usize, tmp1: &[i16], tmp2: &[i16], w: usize, h: usize, weight: i32, bitdepth_max: i32);

#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, tmp1.as_ptr(), tmp2.as_ptr(), w, h, mask.as_ptr(), bitdepth_max,
    [dst.len() == stride * h, tmp1.len() == w * h, tmp2.len() == w * h, mask.len() == w * h, w >= 4, h >= 4, w <= 128, h <= 128, 128 % h == 0, stride >= w])]
fn mask{sfx}(dst: &mut [{px}], stride: usize, tmp1: &[i16], tmp2: &[i16], w: usize, h: usize, mask: &[u8], bitdepth_max: i32);''')

    # w_mask_{420,422,444}
    for ss, div in (("420", 4), ("422", 2), ("444", 1)):
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, tmp1.as_ptr(), tmp2.as_ptr(), w, h, mask.as_mut_ptr(), sign, bitdepth_max,
    [dst.len() == stride * h, tmp1.len() == w * h, tmp2.len() == w * h, mask.len() == w * h / {div}, w >= 4, h >= 4, w <= 128, h <= 128, 128 % h == 0, stride >= w])]
fn w_mask_{ss}{sfx}(dst: &mut [{px}], stride: usize, tmp1: &[i16], tmp2: &[i16], w: usize, h: usize, mask: &mut [u8], sign: i32, bitdepth_max: i32);''')

    # blend / blend_v / blend_h
    out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, tmp.as_ptr(), w, h, mask.as_ptr(),
    [dst.len() == stride * h, tmp.len() == w * h, mask.len() == w * h, w >= 4, h >= 4, w <= 32, h <= 32, 32 % h == 0, stride >= w])]
fn blend{sfx}(dst: &mut [{px}], stride: usize, tmp: &[{px}], w: usize, h: usize, mask: &[u8]);

#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, tmp.as_ptr(), w, h,
    [dst.len() == stride * h, tmp.len() == w * h, w >= 2, h >= 2, w <= 32, stride >= w])]
fn blend_v{sfx}(dst: &mut [{px}], stride: usize, tmp: &[{px}], w: usize, h: usize);

#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, tmp.as_ptr(), w, h,
    [dst.len() == stride * h, tmp.len() == w * h, w >= 2, h >= 2, w <= 128, stride >= w])]
fn blend_h{sfx}(dst: &mut [{px}], stride: usize, tmp: &[{px}], w: usize, h: usize);''')

    # emu_edge
    out.append(f'''
#[bums::check_mem_safe("{f}", bw, bh, iw, ih, x, y, dst.as_mut_ptr(), dst_stride, src.as_ptr(), src_stride,
    [bw >= 1, bh >= 1, iw >= 1, ih >= 1, dst.len() == 320 * (256 + 7), dst_stride % {32 * elem} == 0, bw * {elem} <= dst_stride, (bh - 1) * dst_stride + (bw + 32) * {elem} <= dst.len() * {elem}, src_stride % {32 * elem} == 0, iw * {elem} <= src_stride, (ih - 1) * src_stride + (iw + 32) * {elem} <= src.len() * {elem}])]
fn emu_edge{sfx}(
    bw: usize,
    bh: usize,
    iw: usize,
    ih: usize,
    x: isize,
    y: isize,
    dst: &mut [{px}],
    dst_stride: usize,
    src: &[{px}],
    src_stride: usize,
);''')

    # warp_affine_8x8 / warp_affine_8x8t
    out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), dst_stride, src.as_ptr(), src_stride, abcd.as_ptr(), mx, my, bitdepth_max,
    [dst.len() == dst_stride * 8, src.len() == src_stride * 15, abcd.len() == 4, dst_stride >= 8, src_stride >= 15])]
fn warp_affine_8x8{sfx}(dst: &mut [{px}], dst_stride: usize, src: &[{px}], src_stride: usize, abcd: &[i16], mx: i32, my: i32, bitdepth_max: i32);

#[bums::check_mem_safe("{f}", tmp.as_mut_ptr(), tmp_stride, src.as_ptr(), src_stride, abcd.as_ptr(), mx, my, bitdepth_max,
    [tmp.len() == tmp_stride * 8, src.len() == src_stride * 15, abcd.len() == 4, tmp_stride >= 8, src_stride >= 15])]
fn warp_affine_8x8t{sfx}(tmp: &mut [i16], tmp_stride: usize, src: &[{px}], src_stride: usize, abcd: &[i16], mx: i32, my: i32, bitdepth_max: i32);''')

    # The shared copy/prep inner loops, exported so the filter kernels can
    # branch into them. They take the same registers as `mc`/`mct` minus the
    # subpel offsets.
    if bpc == 8:
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), dst_stride, src.as_ptr(), src_stride, w, h,
    [dst.len() == dst_stride * h, src.len() == src_stride * h, w >= 2, h >= 2, w <= 128, h <= 128, 128 % h == 0, dst_stride >= w, src_stride >= w])]
fn put_neon(dst: &mut [u8], dst_stride: usize, src: &[u8], src_stride: usize, w: usize, h: usize);

#[bums::check_mem_safe("{f}", tmp.as_mut_ptr(), src.as_ptr(), src_stride, w, h,
    [tmp.len() == w * h, src.len() == src_stride * h, w >= 4, h >= 4, w <= 128, h <= 128, 128 % h == 0, src_stride >= w])]
fn prep_neon(tmp: &mut [i16], src: &[u8], src_stride: usize, w: usize, h: usize);''')
    else:
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), dst_stride, src.as_ptr(), src_stride, w, h,
    [dst.len() == dst_stride * h, src.len() == src_stride * h, w >= 2, h >= 2, w <= 128, h <= 128, 128 % h == 0, dst_stride >= w, src_stride >= w])]
fn put_16bpc_neon(dst: &mut [u16], dst_stride: usize, src: &[u16], src_stride: usize, w: usize, h: usize);''')

    return "\n".join(out)


def gen_mc_dotprod():
    out = []
    for ext in ("dotprod", "i8mm"):
        for filt in FILTERS:
            out.append(mc_put("mc_dotprod.S", f"put_8tap_{filt}_8bpc_neon_{ext}", "u8"))
        for filt in FILTERS:
            out.append(mc_prep("mc_dotprod.S", f"prep_8tap_{filt}_8bpc_neon_{ext}", "u8"))
    return "\n".join(out)


