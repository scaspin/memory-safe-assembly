#!/usr/bin/env python3
"""Generate `#[check_mem_safe]` declarations for rav1d's aarch64 assembly.

Every exported C-ABI function in the assembly that `build.rs` links gets one
annotated Rust declaration. The families below mirror the FFI signatures rav1d
itself declares (`wrap_fn_ptr!` in the matching `src/*.rs`), lowered to the
types the macro can size at expansion time:

  * a strided 2D plane becomes a flat slice plus an explicit stride argument,
    tied together by a `buf.len() == stride * rows` precondition;
  * `c_int` dimensions that appear in preconditions become `usize`, so the
    runtime asserts the macro emits type-check;
  * arrays of pointers (sgr's `a_ptrs`/`b_ptrs`, `save_tmvs`'s `rr`) become
    `&[usize]`, which bounds the pointer array itself but not its targets.

Run from the crate root:  python3 gen-annotations.py
"""

import os
import re
import subprocess
import sys

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "asm")

HEADER = '''//! {title}
//!
//! Generated by `gen-annotations.py` -- edit that script, not this file.
#![allow(dead_code)]

use bums_macros as bums;
'''

# ---------------------------------------------------------------------------
# Per-bitdepth helpers
# ---------------------------------------------------------------------------


def pixel(bpc):
    return "u8" if bpc == 8 else "u16"


def suffix(bpc):
    return f"_{bpc}bpc_neon"


# ---------------------------------------------------------------------------
# ipred.S / ipred16.S
# ---------------------------------------------------------------------------

ANGULAR = [
    "ipred_dc_128",
    "ipred_dc",
    "ipred_dc_top",
    "ipred_dc_left",
    "ipred_v",
    "ipred_h",
    "ipred_paeth",
    "ipred_smooth",
    "ipred_smooth_v",
    "ipred_smooth_h",
    "ipred_filter",
]
CFL_PRED = ["ipred_cfl_128", "ipred_cfl", "ipred_cfl_top", "ipred_cfl_left"]
CFL_AC = ["ipred_cfl_ac_420", "ipred_cfl_ac_422", "ipred_cfl_ac_444"]
Z13_FILL = ["ipred_z1_fill1", "ipred_z1_fill2", "ipred_z3_fill1", "ipred_z3_fill2"]
Z2_FILL = ["ipred_z2_fill1", "ipred_z2_fill2", "ipred_z2_fill3"]


def gen_ipred(bpc):
    px = pixel(bpc)
    sfx = suffix(bpc)
    f = f"ipred{'' if bpc == 8 else '16'}.S"
    # The edge helpers step a whole 128-bit vector per iteration, so the element
    # count they accept is fixed by the pixel size.
    per_iter = 16 // (1 if bpc == 8 else 2)
    out = []

    # angular_ipred: writes an h x w block of `dst`, reads the edge buffer
    # around `topleft`. The caller's edge buffer is 257 elements with the
    # corner pixel at its middle (dav1d's `edge_buf` / rav1d's `topleft_off`),
    # so `topleft` is a pointer 128 elements in and the left edge sits at
    # negative offsets from it.
    # The block size bounds the jump-table index each function derives from
    # clz(width) (and clz(height) where it dispatches on both): past it the
    # index leaves the table. Filter intra is limited to 32x32.
    for name in ANGULAR:
        most = 32 if name == "ipred_filter" else 64
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, topleft.as_ptr().add(128), width, height, angle, max_width, max_height, bitdepth_max,
    [dst.len() == stride * height, topleft.len() == 257, width >= 4, height >= 4, width <= {most}, height <= {most}, {most} % height == 0, stride >= width])]
fn {name}{sfx}(
    dst: &mut [{px}],
    stride: usize,
    topleft: &[{px}],
    width: usize,
    height: usize,
    angle: i32,
    max_width: i32,
    max_height: i32,
    bitdepth_max: i32,
);''')

    # cfl_pred
    for name in CFL_PRED:
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, topleft.as_ptr().add(128), width, height, ac.as_ptr(), alpha, bitdepth_max,
    [dst.len() == stride * height, topleft.len() == 257, ac.len() == width * height, width >= 4, height >= 4, width <= 32, height <= 32, 32 % height == 0, stride >= width])]
fn {name}{sfx}(
    dst: &mut [{px}],
    stride: usize,
    topleft: &[{px}],
    width: usize,
    height: usize,
    ac: &[i16],
    alpha: i32,
    bitdepth_max: i32,
);''')

    # cfl_ac
    # Chroma of at most a 32x32 luma block: 4:2:0 halves both sides, 4:2:2
    # only the width.
    for name in CFL_AC:
        wmax = 32 if name.endswith("444") else 16
        hmax = 16 if name.endswith("420") else 32
        out.append(f'''
#[bums::check_mem_safe("{f}", ac.as_mut_ptr(), y.as_ptr(), stride, w_pad, h_pad, cw, ch,
    [ac.len() == cw * ch, y.len() == stride * ch, cw >= 4, ch >= 4, cw <= {wmax}, ch <= {hmax}, {hmax} % ch == 0, stride >= cw, w_pad >= 0, w_pad <= 3, h_pad >= 0, h_pad <= 3])]
fn {name}{sfx}(
    ac: &mut [i16],
    y: &[{px}],
    stride: usize,
    w_pad: i32,
    h_pad: i32,
    cw: usize,
    ch: usize,
);''')

    # pal_pred
    out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, pal.as_ptr(), idx.as_ptr(), w, h,
    [dst.len() == stride * h, pal.len() == 8, idx.len() == w * h / 2, w >= 4, h >= 4, w <= 64, h <= 64, 64 % h == 0, stride >= w])]
fn pal_pred{sfx}(
    dst: &mut [{px}],
    stride: usize,
    pal: &[{px}],
    idx: &[u8],
    w: usize,
    h: usize,
);''')

    # z13_fill
    for name in Z13_FILL:
        if name.endswith("fill2"):
            edge = "64 + 64 * (64 + 15) * 2 + 16" if name.startswith("ipred_z1") else "64 + 64 + (64 + 15) * 2"
            elem = 1 if bpc == 8 else 2
            pre = f"dst.len() * {elem} == stride * height, topleft.len() == {edge}, max_base_xy == 2 * (width + height) - 2, width + height <= 16, width >= 4, height >= 4, width % 4 == 0, height % 4 == 0, stride >= width * {elem}, dxy >= 0, dxy <= 102"
        else:
            pre = "dst.len() == stride * height, topleft.len() == 2 * width + 1, max_base_xy + 8 <= topleft.len(), width >= 4, height >= 4, width <= 64, height <= 64, 64 % height == 0, stride >= width"
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, topleft.as_ptr(), width, height, dxy, max_base_xy,
    [{pre}])]
fn {name}{sfx}(
    dst: &mut [{px}],
    stride: usize,
    topleft: &[{px}],
    width: usize,
    height: usize,
    dxy: i32,
    max_base_xy: usize,
);''')

    # z2_fill
    for name in Z2_FILL:
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, top.as_ptr(), left.as_ptr(), width, height, dx, dy,
    [dst.len() == stride * height, top.len() == 2 * width + 1, left.len() == 2 * height + 1, width >= 4, height >= 4, width <= 64, height <= 64, 64 % height == 0, stride >= width])]
fn {name}{sfx}(
    dst: &mut [{px}],
    stride: usize,
    top: &[{px}],
    left: &[{px}],
    width: usize,
    height: usize,
    dx: i32,
    dy: i32,
);''')

    # z1_upsample_edge / z2_upsample_edge / z1_filter_edge / reverse / pixel_set
    out.append(f'''
#[bums::check_mem_safe("{f}", out.as_mut_ptr(), hsz, in_0.as_ptr(), end, bitdepth_max,
    [out.len() == hsz * 2, in_0.len() == hsz + 1, hsz >= 4, hsz <= 64])]
fn ipred_z1_upsample_edge{sfx}(out: &mut [{px}], hsz: usize, in_0: &[{px}], end: i32, bitdepth_max: i32);

#[bums::check_mem_safe("{f}", out.as_mut_ptr(), hsz, in_0.as_ptr(), bitdepth_max,
    [out.len() == hsz * 2, in_0.len() == hsz + 1, hsz >= 4, hsz <= 64])]
fn ipred_z2_upsample_edge{sfx}(out: &mut [{px}], hsz: usize, in_0: &[{px}], bitdepth_max: i32);

#[bums::check_mem_safe("{f}", out.as_mut_ptr(), sz, in_0.as_ptr(), end, strength,
    [out.len() == sz, in_0.len() == sz + 1, sz >= 4, sz <= 128, strength >= 1, strength <= 3])]
fn ipred_z1_filter_edge{sfx}(out: &mut [{px}], sz: usize, in_0: &[{px}], end: i32, strength: i32);

#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), src.as_ptr_range().end, n,
    [dst.len() == src.len(), src.len() == n, n >= {per_iter}, n % {per_iter} == 0])]
fn ipred_reverse{sfx}(dst: &mut [{px}], src: &[{px}], n: usize);

#[bums::check_mem_safe("{f}", out.as_mut_ptr(), px, n, [out.len() == n, n >= {per_iter}, n % {per_iter} == 0])]
fn ipred_pixel_set{sfx}(out: &mut [{px}], px: {px}, n: usize);''')

    return "\n".join(out)


