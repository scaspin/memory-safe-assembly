def gen_itx(bpc, names):
    px = pixel(bpc)
    f = f"itx{'' if bpc == 8 else '16'}.S"
    coef = "i16" if bpc == 8 else "i32"
    out = []
    for name in names:
        m = re.search(r"_(\d+)x(\d+)_", name)
        w, h = int(m.group(1)), int(m.group(2))
        # Only the low 32x32 coefficients are ever stored for larger transforms.
        n_coeff = min(w, 32) * min(h, 32)
        out.append(f'''
#[bums::check_mem_safe("{f}", dst.as_mut_ptr(), stride, coeff.as_mut_ptr(), eob, bitdepth_max,
    [dst.len() == stride * {h}, stride >= {w}, coeff.len() == {n_coeff}, eob < {n_coeff}])]
fn {name}(dst: &mut [{px}], stride: usize, coeff: &mut [{coef}], eob: usize, bitdepth_max: i32);''')
    return "\n".join(out)


