# Generates ffmpeg-playground/src/vvc.rs from libavcodec/aarch64/vvc/dsp_init.c.
import re, sys, collections
init = open(sys.argv[2]).read()
ex = {l.split("\t")[1].strip(): re.sub(r"^(h26x|vvc)_", "", l.split("\t")[0].split("aarch64_")[1]) + ".S" for l in open(sys.argv[1])}
# Walk the init function: bit depth from `bd == N`, chained assignments.
widths = collections.defaultdict(set); kind = {}; depth = {}
bd = 8; pending = []
for line in init[init.index("void ff_vvc_dsp_init_aarch64"):].splitlines():
    m = re.search(r"bd == (\d+)", line)
    if m: bd = int(m.group(1))
    m = re.search(r"c->inter\.(put|put_uni|put_uni_w)\[(\d)\]\[(\d)\]\[(\d)\]\[(\d)\]\s*=\s*(\w+)?;?", line)
    if m:
        pending.append(m.groups()[:5])
        if m.group(6):
            name = m.group(6)
            for table, ch, idx, v, h in pending:
                widths[name].add(1 << (int(idx) + 1))
                kind[name] = (table, int(ch), int(v), int(h))
                depth[name] = bd
            pending = []
out = ['''//! libavcodec/aarch64/vvc inter.S and the h26x MC VVC calls, as
//! vvc/dsp_init.c assigns them. Generated by gen/vvc.py.
//!
//! VVC's MAX_PB_SIZE is 128: intermediate int16 blocks have that stride.
//! Luma filters are 8-tap (3 before, 4 after), chroma 4-tap (1, 2); hf/vf
//! point at one filter's taps. A function the table shares across widths is
//! checked for each. Heights are even, 2..128. High bit depths are u16 with
//! byte strides.
//!
//! The MC source is whole rows: the filter footprint plus one more row and
//! 16 bytes. inter.c (emulated_edge_no_wrap) reads in place only when the
//! block and its filter margin lie strictly inside the picture (or
//! subpicture), so a picture row lies below the footprint, and otherwise from
//! edge_emu_buffer (stride (MAX_PB_SIZE + 32) * 2, as many rows); a frame
//! plane's pool adds 16 + STRIDE_ALIGN - 1 bytes after its last row. The NEON
//! code loads whole vectors past the footprint, which this keeps in bounds.
//! DMVR fetches the block plus 2 samples each side (pred_w = block_w + 4 with
//! block_w in {8, 16}); its h/v/hv variants read one more column/row. BDOF
//! reads one sample around each 8/16 block from the decoder's tmp arrays,
//! entered PROF_TEMP_OFFSET (160) samples in. SAD compares the DMVR tmp
//! arrays at offsets dx, dy in 0..4.
use bums_macros as bums;
''']
def emit(name, args, pre, sig):
    if name not in ex:
        print("missing", name, file=sys.stderr); return
    out.append(f'''#[bums::check_mem_safe("{ex[name]}", {", ".join(args)},
    [{", ".join(pre)}])]
fn {name}({sig});
''')
for name in sorted(widths):
    table, ch, v, h = kind[name]
    ws = sorted(widths[name]); bd = depth[name]
    ty, el = ("u8", 1) if bd == 8 else ("u16", 2)
    row = "src_stride" if el == 1 else "src_stride / 2"
    before, after = (1, 2) if ch else (3, 4)
    bh, ah = (before, after) if h else (0, 0)
    bv, av = (before, after) if v else (0, 0)
    taps = 4 if ch else 8
    wcond = " || ".join(f"width == {x}" for x in ws)
    # Whole rows: the footprint plus a row and 16 bytes (see the module doc).
    pre = [f"src.len() == (height + {bv + av + 1}) * {row} + {16 // el}", f"src_stride >= {(max(ws) + bh + ah) * el}",
           "src_stride <= 1073741824", "height % 2 == 0", "height >= 2", "height <= 128", wcond,
           f"hf.len() == {taps}", f"vf.len() == {taps}"] + (["src_stride % 2 == 0"] if el == 2 else [])
    src = f"src.as_ptr().add({bv} * {row} + {bh})"
    if table == "put":
        args = ["dst.as_mut_ptr()", src, "src_stride", "height", "hf.as_ptr()", "vf.as_ptr()", "width"]
        pre.insert(0, "dst.len() == 16384")
        sig = f"dst: &mut [i16], src: &[{ty}], src_stride: usize, height: usize, hf: &[i8], vf: &[i8], width: usize"
    else:
        drow = "dst_stride" if el == 1 else "dst_stride / 2"
        pre = [f"dst.len() == (height - 1) * {drow} + width", f"dst_stride >= {max(ws) * el}", "dst_stride <= 1073741824"] + pre
        mid = ["denom", "wx", "ox"] if table == "put_uni_w" else []
        args = ["dst.as_mut_ptr()", "dst_stride", src, "src_stride", "height"] + mid + ["hf.as_ptr()", "vf.as_ptr()", "width"]
        sig = f"dst: &mut [{ty}], dst_stride: usize, src: &[{ty}], src_stride: usize, height: usize" + "".join(f", {a}: i32" for a in mid) + ", hf: &[i8], vf: &[i8], width: usize"
        if mid: pre.append("denom <= 14")
    note = f"// called for widths {ws}\n" if len(ws) > 1 else ""
    out[-1:] = out[-1:]
    if note: out.append(note.rstrip("\n"))
    emit(name, args, pre, sig)
pow2 = " * ".join(f"(width - {x})" for x in (2, 4, 8, 16, 32, 64, 128)) + " == 0"
pow2h = pow2.replace("width", "height")
for bd in (8, 10, 12):
    ty, el = ("u8", 1) if bd == 8 else ("u16", 2)
    drow = "dst_stride" if el == 1 else "dst_stride / 2"
    common = [f"dst.len() == (height - 1) * {drow} + width", "src0.len() == 16384", "src1.len() == 16384",
              pow2, pow2h, f"dst_stride >= {128 * el}", "dst_stride <= 1073741824"] + (["dst_stride % 2 == 0"] if el == 2 else [])
    emit(f"ff_vvc_avg_{bd}_neon", ["dst.as_mut_ptr()", "dst_stride", "src0.as_ptr()", "src1.as_ptr()", "width", "height"], common,
         f"dst: &mut [{ty}], dst_stride: usize, src0: &[i16], src1: &[i16], width: usize, height: usize")
    emit(f"ff_vvc_w_avg_{bd}_neon", ["dst.as_mut_ptr()", "dst_stride", "src0.as_ptr()", "src1.as_ptr()", "width", "height", "w0_w1", "offset_shift"], common,
         f"dst: &mut [{ty}], dst_stride: usize, src0: &[i16], src1: &[i16], width: usize, height: usize, w0_w1: u64, offset_shift: u64")
    row = "src_stride" if el == 1 else "src_stride / 2"
    for v, h, nm in ((0, 0, ""), (0, 1, "h_"), (1, 0, "v_"), (1, 1, "hv_")):
        emit(f"ff_vvc_dmvr_{nm}{bd}_neon", ["dst.as_mut_ptr()", "src.as_ptr()", "src_stride", "height", "mx", "my", "width"],
             ["dst.len() == 16384", f"src.len() == (height - 1 + {v}) * {row} + width + {h}",
              "(width - 12) * (width - 20) == 0", "(height - 12) * (height - 20) == 0", f"src_stride >= {21 * el}", "src_stride <= 1073741824",
              "mx <= 15", "my <= 15"] + (["src_stride % 2 == 0"] if el == 2 else []),
             f"dst: &mut [i16], src: &[{ty}], src_stride: usize, height: usize, mx: usize, my: usize, width: usize")
    emit(f"ff_vvc_apply_bdof_{bd}_neon", ["dst.as_mut_ptr()", "dst_stride", "src0.as_ptr().add(160)", "src1.as_ptr().add(160)", "block_w", "block_h"],
         [f"dst.len() == (block_h - 1) * {drow} + block_w", "src0.len() == 16384", "src1.len() == 16384",
          "(block_w - 8) * (block_w - 16) == 0", "(block_h - 8) * (block_h - 16) == 0", f"dst_stride >= {16 * el}", "dst_stride <= 1073741824"]
         + (["dst_stride % 2 == 0"] if el == 2 else []),
         f"dst: &mut [{ty}], dst_stride: usize, src0: &[i16], src1: &[i16], block_w: usize, block_h: usize")
emit("ff_vvc_sad_neon", ["src0.as_ptr()", "src1.as_ptr()", "dx", "dy", "block_w", "block_h"],
     ["src0.len() == 16384", "src1.len() == 16384", "dx <= 4", "dy <= 4", "(block_w - 8) * (block_w - 16) == 0", "(block_h - 8) * (block_h - 16) == 0"],
     "src0: &[i16], src1: &[i16], dx: usize, dy: usize, block_w: usize, block_h: usize")
out.append(open(__import__("os").path.join(__import__("os").path.dirname(__file__), "..", "extra", "vvc.rs")).read().strip("\n") + "\n")  # hand-written tail
print("\n".join(out))
