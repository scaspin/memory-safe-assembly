# Generates ffmpeg-playground/src/hevc_mc.rs from FFmpeg's aarch64 HEVC MC init
# table (hevcdsp_init_aarch64.c): each function's argument layout, filter
# margins, and the widths the table calls it with.
import re, sys
files = {l.split("\t")[1].strip(): l.split("\t")[0].split("h26x_")[1] + ".S" for l in open(sys.argv[1])
         if l.split("\t")[0].endswith(("h26x_qpel_neon", "h26x_epel_neon"))}
exports = list(files)
pat = re.compile(r"ff_hevc_put_hevc_(\w+?)(\d+)_8_neon(_i8mm)?$")

def widths(fam, w, i8mm):
    shared32 = fam in ("qpel_uni_w_h", "epel_h", "epel_uni_w_h") and not i8mm
    qpel_h = fam in ("qpel_h", "qpel_uni_h", "qpel_bi_h") and not i8mm
    if qpel_h:
        return {12: [12, 24], 32: [32, 48, 64]}.get(w, [w])
    if shared32:
        return {32: [32, 48, 64]}.get(w, [w])
    if fam == "pel_bi_w_pixels":
        return {24: [24, 48], 32: [32, 64]}.get(w, [w])
    return [w]

out = ['''//! libavcodec/aarch64/h26x qpel_neon.S and epel_neon.S, as HEVC calls them
//! (hevcdsp_init_aarch64.c). Generated by gen/hevc_mc.py.
//!
//! qpel is the 8-tap luma filter (3 pixels before, 4 after), epel the 4-tap
//! chroma filter (1 before, 2 after), each only in the direction it filters.
//! Intermediate int16 blocks (dst of put_hevc_*, src2 of the bi functions)
//! have a stride of MAX_PB_SIZE = 64 elements and are the decoder's
//! tmp[MAX_PB_SIZE * MAX_PB_SIZE] (hevcdec.h), entered at its start. A function the table shares
//! across widths (fn32 for 32, 48 and 64) is checked for each of them. Heights
//! are even, 2..64 (4:2:0 chroma blocks can be 2 high); strides are positive.
//!
//! The source is whole rows: the filter footprint (h + taps - 1 rows from
//! `taps/2 - 1` columns left of the block) plus one more row and 16 bytes.
//! hevcdec.c reads in place only when the block and its filter margin sit
//! strictly inside the picture (so a picture row lies below the footprint),
//! and otherwise from edge_emu_buffer, stride 80, twice the footprint's rows;
//! a frame plane's pool adds 16 + STRIDE_ALIGN - 1 bytes after its last row.
//! The NEON code loads whole vectors past the footprint (up to 15 bytes on a
//! row, and the hv filters one row below), which this keeps in bounds.
//! The weighted variants' denom/wx/ox are values only.
use bums_macros as bums;
''']
for name in exports:
    m = pat.match(name)
    if not m:
        print("skip", name, file=sys.stderr); continue
    fam, w, i8mm = m.group(1), int(m.group(2)), bool(m.group(3))
    ws = widths(fam, w, i8mm)
    taps = 8 if fam.startswith("qpel") else 4 if fam.startswith("epel") else 0
    direction = fam.rsplit("_", 1)[-1] if taps else ""
    kind = "plain"
    for k in ("uni_w", "bi_w", "uni", "bi"):
        if f"_{k}_" in f"_{fam}_":
            kind = k; break
    before, after = {8: (3, 4), 4: (1, 2), 0: (0, 0)}[taps]
    bh, ah = (before, after) if "h" in direction else (0, 0)
    bv, av = (before, after) if "v" in direction else (0, 0)
    fmax = {8: 3, 4: 7, 0: 0}[taps]
    mx_lo = 1 if "h" in direction else 0
    my_lo = 1 if "v" in direction else 0
    wmax = max(ws)
    wcond = " || ".join(f"width == {x}" for x in ws)
    src = f"src.as_ptr().add({bv} * srcstride + {bh})" if (bv or bh) else "src.as_ptr()"
    pre = [f"src.len() == (height + {bv + av + 1}) * srcstride + 16",
           f"srcstride >= {wmax + bh + ah}", "srcstride <= 1073741824",
           "height % 2 == 0", "height >= 2", "height <= 64", wcond,
           f"mx >= {mx_lo}", f"mx <= {fmax}", f"my >= {my_lo}", f"my <= {fmax}"]
    if kind == "plain":
        args = ["dst.as_mut_ptr()", src, "srcstride", "height", "mx", "my", "width"]
        sig = "dst: &mut [i16], src: &[u8], srcstride: usize, height: usize, mx: usize, my: usize, width: usize"
        pre.insert(0, "dst.len() == 4096")
    else:
        pre.insert(0, "dst.len() == (height - 1) * dststride + width")
        pre += [f"dststride >= {wmax}", "dststride <= 1073741824"]
        head = ["dst.as_mut_ptr()", "dststride", src, "srcstride"]
        headsig = "dst: &mut [u8], dststride: usize, src: &[u8], srcstride: usize"
        if kind in ("bi", "bi_w"):
            head.append("src2.as_ptr()"); headsig += ", src2: &[i16]"
            pre.append("src2.len() == 4096")
        mid = {"uni": [], "bi": [], "uni_w": ["denom", "wx", "ox"], "bi_w": ["denom", "wx0", "wx1", "ox"]}[kind]
        args = head + ["height"] + mid + ["mx", "my", "width"]
        sig = headsig + ", height: usize" + "".join(f", {a}: i32" for a in mid) + ", mx: usize, my: usize, width: usize"
        if mid: pre.append("denom <= 14")
    note = f"// called for widths {ws}\n" if len(ws) > 1 else ""
    out.append(f'''{note}#[bums::check_mem_safe("{files[name]}", {", ".join(args)},
    [{", ".join(pre)}])]
fn {name}({sig});
''')
print("\n".join(out))
