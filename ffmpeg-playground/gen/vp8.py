# Generates ffmpeg-playground/src/vp8.rs.
import re, sys
ex = [l.split("\t")[1].strip() for l in open(sys.argv[1]) if "vp8dsp" in l.split("\t")[0]]
out = ['''//! libavcodec/aarch64 vp8dsp_neon.S. Generated by gen/vp8.py.
//!
//! MC: a w-wide block of h rows (VP8 partitions give h in {4, 8, 16}, and
//! at most 8 for the 4-wide functions); the
//! 4-tap filters read 1 sample before and 2 after, the 6-tap ones 2 and 3,
//! bilinear 1 after, each in the direction it filters. The epel filters index
//! subpel_filters[mx - 1], so a filtering direction has mx (my) in 1..7.
//! Loop filters touch 4 samples each side of a 16 (luma) or 8 (chroma) sample
//! edge; h filters a vertical edge, v a horizontal one.
use bums_macros as bums;
''']
def emit(name, args, pre, sig):
    out.append(f'''#[bums::check_mem_safe("vp8dsp_neon.S", {", ".join(args)},
    [{", ".join(pre)}])]
fn {name}({sig});
''')
for name in ex:
    m = re.match(r"ff_put_vp8_(pixels|epel|bilin)(\d+)(?:_(h\d?)?(v\d?)?)?_neon$", name)
    if m:
        kind, w, hd, vd = m.group(1), int(m.group(2)), m.group(3) or "", m.group(4) or ""
        tap = lambda d: (0, 0) if not d else ((0, 1) if kind == "bilin" else {"4": (1, 2), "6": (2, 3)}[d[1:]])
        bh, ah = tap(hd); bv, av = tap(vd)
        # 4-wide blocks are 4x4 sub-blocks or the 4x8 chroma of an 8x16
        # partition (vp8.c vp8_mc_part); the 4-wide 2-D filters keep h + 5
        # (h + 3) rows on a 52 (44) byte stack temp, which fits h <= 8.
        hmax = 8 if w == 4 else 16
        hmin = 4 if w < 16 else 8
        if hd or vd:
            # In place (vp8_mc_luma/chroma read the frame only when the
            # footprint is strictly inside the picture): whole rows plus one
            # row and 16 bytes. Otherwise edge_emu_buffer, 21 rows of 32
            # bytes, which src points into at the filter's margins.
            emu = 672 if kind == "epel" else 672 - 2 - (64 if vd else 0)
            srclen = (f"src.len() == (h + {bv + av + 1}) * srcstride + 16"
                      f" || (srcstride == 32 && src.len() == {emu})")
        else:
            srclen = f"src.len() == (h - 1 + {bv + av}) * srcstride + {w + bh + ah}"
        pre = [f"dst.len() == (h - 1) * dststride + {w}", srclen,
               f"dststride >= {w}", f"srcstride >= {w + bh + ah}", "dststride <= 1073741824", "srcstride <= 1073741824",
               "h % 4 == 0", f"h >= {hmin}", f"h <= {hmax}",
               f"mx >= {1 if hd and kind == 'epel' else 0}", "mx <= 7", f"my >= {1 if vd and kind == 'epel' else 0}", "my <= 7"]
        emit(name, ["dst.as_mut_ptr()", "dststride", f"src.as_ptr().add({bv} * srcstride + {bh})", "srcstride", "h", "mx", "my"],
             pre, "dst: &mut [u8], dststride: usize, src: &[u8], srcstride: usize, h: usize, mx: usize, my: usize")
        continue
    m = re.match(r"ff_vp8_(h|v)_loop_filter(16|8uv)(_inner|_simple)?_neon$", name)
    if m:
        d, kind, variant = m.group(1), m.group(2), m.group(3) or ""
        ln = 16 if kind == "16" else 8
        if d == "v":
            ptr = lambda b: f"{b}.as_mut_ptr().add(4 * stride)"; length = lambda b: f"{b}.len() == 7 * stride + {ln}"; smin = ln
        else:
            ptr = lambda b: f"{b}.as_mut_ptr().add(4)"; length = lambda b: f"{b}.len() == {ln - 1} * stride + 8"; smin = 8
        bufs = ["dst"] if kind == "16" else ["dst_u", "dst_v"]
        tail = ["flim"] if variant == "_simple" else ["flim_e", "flim_i", "hev_thresh"]
        emit(name, [ptr(b) for b in bufs] + ["stride"] + tail,
             [length(b) for b in bufs] + [f"stride >= {smin}", "stride <= 1073741824"],
             ", ".join(f"{b}: &mut [u8]" for b in bufs) + ", stride: usize" + "".join(f", {t}: i32" for t in tail))
        continue
    print("skip", name, file=sys.stderr)
out.append('''#[bums::check_mem_safe("vp8dsp_neon.S", block.as_mut_ptr(), dc.as_mut_ptr(), [block.len() == 256, dc.len() == 16])]
fn ff_vp8_luma_dc_wht_neon(block: &mut [i16], dc: &mut [i16]);

#[bums::check_mem_safe("vp8dsp_neon.S", dst.as_mut_ptr(), block.as_mut_ptr(), stride,
    [dst.len() == 3 * stride + 4, block.len() == 16, stride >= 4, stride <= 1073741824])]
fn ff_vp8_idct_add_neon(dst: &mut [u8], block: &mut [i16], stride: usize);

#[bums::check_mem_safe("vp8dsp_neon.S", dst.as_mut_ptr(), block.as_mut_ptr(), stride,
    [dst.len() == 3 * stride + 4, block.len() == 16, stride >= 4, stride <= 1073741824])]
fn ff_vp8_idct_dc_add_neon(dst: &mut [u8], block: &mut [i16], stride: usize);

// Four 4x4 blocks side by side.
#[bums::check_mem_safe("vp8dsp_neon.S", dst.as_mut_ptr(), block.as_mut_ptr(), stride,
    [dst.len() == 3 * stride + 16, block.len() == 64, stride >= 16, stride <= 1073741824])]
fn ff_vp8_idct_dc_add4y_neon(dst: &mut [u8], block: &mut [i16], stride: usize);

// Four 4x4 blocks in a 2 x 2 square.
#[bums::check_mem_safe("vp8dsp_neon.S", dst.as_mut_ptr(), block.as_mut_ptr(), stride,
    [dst.len() == 7 * stride + 8, block.len() == 64, stride >= 8, stride <= 1073741824])]
fn ff_vp8_idct_dc_add4uv_neon(dst: &mut [u8], block: &mut [i16], stride: usize);
''')
print("\n".join(out))
